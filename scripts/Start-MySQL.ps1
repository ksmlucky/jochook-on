$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Use-DevTools.ps1')
Import-HanaEnvironment
if (-not $env:HANA_MYSQL_HOME) { throw 'MySQL 8.4 was not found in LocalAppData\Programs\MySQL.' }
# This launcher only manages its own local database, never another MySQL installation.
if ($env:MYSQL_HOST -ne '127.0.0.1' -or $env:MYSQL_PORT -ne '3307') { throw 'This local launcher requires MYSQL_HOST=127.0.0.1 and MYSQL_PORT=3307.' }
if ($env:MYSQL_DATABASE -notmatch '^\w+$' -or $env:MYSQL_USER -notmatch '^\w+$') { throw 'Use simple local database and user names.' }
if ($env:MYSQL_PASSWORD -notmatch '^[a-zA-Z0-9]{20,}$' -or $env:MYSQL_ROOT_PASSWORD -notmatch '^[a-zA-Z0-9]{20,}$') { throw 'This initializer expects the passwords generated by Initialize-Local.ps1.' }
$taskRoot = Split-Path -Parent $PSScriptRoot
$taskState = Join-Path $taskRoot '.local'
$taskData = Join-Path $taskState 'mysql-data'
New-Item -ItemType Directory -Path $taskState -Force | Out-Null
$taskClientFile = Join-Path $taskState 'mysql-app.cnf'
$taskClientText = "[client]`nhost=127.0.0.1`nport=3307`nuser=$($env:MYSQL_USER)`npassword=$($env:MYSQL_PASSWORD)`nprotocol=tcp`n"
[IO.File]::WriteAllText($taskClientFile, $taskClientText, [Text.UTF8Encoding]::new($false))
$taskMysqlExe = Join-Path $env:HANA_MYSQL_HOME 'bin\mysql.exe'
$taskMysqldExe = Join-Path $env:HANA_MYSQL_HOME 'bin\mysqld.exe'
$taskBootstrap = Join-Path $taskState 'mysql-bootstrap.sql'
function Test-MySQLConnection {
    $ErrorActionPreference = 'Continue'
    & $taskMysqlExe "--defaults-extra-file=$taskClientFile" --connect-timeout=2 --execute='SELECT 1' 2>$null | Out-Null
    return $LASTEXITCODE -eq 0
}
try {
    if (Test-MySQLConnection) { Write-Output 'MySQL is ready at 127.0.0.1:3307.'; return }
    $taskTcp = New-Object Net.Sockets.TcpClient
    try { $taskTcp.Connect('127.0.0.1', 3307); throw 'Port 3307 is already occupied by a database that does not match this project.' }
    catch [Net.Sockets.SocketException] { }
    finally { $taskTcp.Dispose() }

    $taskFresh = -not (Test-Path -LiteralPath $taskData)
    if ($taskFresh) {
        & $taskMysqldExe --no-defaults "--basedir=$($env:HANA_MYSQL_HOME)" "--datadir=$taskData" --initialize-insecure ('--log-error=' + (Join-Path $taskState 'mysql-initialize.log'))
        if ($LASTEXITCODE -ne 0) { throw 'MySQL initialization failed. See .local/mysql-initialize.log.' }
        $taskSql = "ALTER USER 'root'@'localhost' IDENTIFIED BY '$($env:MYSQL_ROOT_PASSWORD)';`nCREATE DATABASE IF NOT EXISTS $($env:MYSQL_DATABASE) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;`nCREATE USER IF NOT EXISTS '$($env:MYSQL_USER)'@'localhost' IDENTIFIED BY '$($env:MYSQL_PASSWORD)';`nGRANT ALL PRIVILEGES ON $($env:MYSQL_DATABASE).* TO '$($env:MYSQL_USER)'@'localhost';`n"
        [IO.File]::WriteAllText($taskBootstrap, $taskSql, [Text.UTF8Encoding]::new($false))
    }
    $taskArgs = @('--no-defaults', ('--basedir="' + $env:HANA_MYSQL_HOME + '"'), ('--datadir="' + $taskData + '"'), '--port=3307', '--bind-address=127.0.0.1', '--mysqlx=0', '--skip-log-bin', '--console')
    if (Test-Path -LiteralPath $taskBootstrap) { $taskArgs += '--init-file="' + $taskBootstrap + '"' }
    $taskProcess = Start-Process -FilePath $taskMysqldExe -ArgumentList $taskArgs -WindowStyle Hidden -PassThru -RedirectStandardOutput (Join-Path $taskState 'mysql.stdout.log') -RedirectStandardError (Join-Path $taskState 'mysql.stderr.log')
    $taskReady = $false
    for ($taskAttempt = 0; $taskAttempt -lt 30; $taskAttempt++) {
        if ($taskProcess.HasExited) { throw 'MySQL stopped unexpectedly. See .local/mysql.stderr.log.' }
        if (Test-MySQLConnection) { $taskReady = $true; break }
        Start-Sleep -Seconds 1
    }
    if (-not $taskReady) { throw 'MySQL did not become ready. See .local/mysql.stderr.log.' }
    if (Test-Path -LiteralPath $taskBootstrap) { Remove-Item -LiteralPath $taskBootstrap }
    Write-Output 'MySQL is ready at 127.0.0.1:3307. Data is stored in .local/mysql-data.'
} finally {
    if (Test-Path -LiteralPath $taskClientFile) { Remove-Item -LiteralPath $taskClientFile }
}
